"""Файловый флаг остановки идущей сессии.

Механика: бот (или CLI) вызывает touch() — создаёт файл-маркер;
цикл лайков в AutoLiker.run() перед каждым постом проверяет exists()
и выходит из цикла; при старте новой сессии clear() убирает устаревший
маркер, чтобы случайный «стоп» не убил следующую сессию.

Файл, а не сигнал: процесс сессии запускается через subprocess.Popen
из Commands.start(), сигнал послать нечем (PID не передаётся обратно),
а файловый флаг работает между процессами без IPC.

Идемпотентность: touch()/clear()/exists() не падают при повторном
вызове или отсутствующем файле — стоп-кнопка безопасна при ределивере.
"""

from pathlib import Path

# Маркер рядом с сессионной блокировкой: тот же каталог src/, то же
# жизненное пространство демона и сессии
_STOP_FLAG_PATH = Path(__file__).parent / ".autoliker.stop"


class StopFlag:
    """Файловый флаг «останови текущую сессию» между процессами."""

    def __init__(self, path: Path = _STOP_FLAG_PATH) -> None:
        """Путь маркера по умолчанию — src/.autoliker.stop."""
        self._path = path

    def touch(self) -> None:
        """Ставит флаг: создаёт файл. Идемпотентно — повтор не ошибка."""
        self._path.touch()

    def clear(self) -> None:
        """Снимает флаг: удаляет файл. Идемпотентно — нет файла не ошибка."""
        self._path.unlink(missing_ok=True)

    def exists(self) -> bool:
        """Проверяет флаг: True — запрошена остановка."""
        return self._path.exists()
